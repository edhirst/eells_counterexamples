"""LaTeX tables of the coefficients of Wbar (Appendix of the paper).

Usage:  python -m numerics.make_tables --coefficients data/Wbar_D40.json --out certificate/output/coefficients_D40.tex
The values are printed with the shortest decimal representation that round-trips to the same
IEEE double (Python's repr), so the table *is* the polynomial used by the certificate.
"""
from __future__ import annotations

import argparse
from pathlib import Path

from eells.fields import load_coefficients


def latex_longtable(modes, values, D, columns=2, max_degree=None):
    rows = [(m, v) for m, v in zip(modes, values) if max_degree is None or m.l <= max_degree]
    n = len(rows)
    per = -(-n // columns)
    head = " & ".join(["$\\ell$ & type & $m$ & $n$ & $j$ & $a_k$"] * columns)
    spec = "|".join(["rcrrrl"] * columns)
    out = ["% generated by numerics/make_tables.py; every a_k is an exact IEEE double (shortest round-trip decimal)",
           f"\\begin{{longtable}}{{{spec}}}",
           f"\\caption{{Coefficients $a_k$ of $\\bar W=\\sum_k a_k\\Psi_k$ in the orthonormal basis of "
           f"Proposition~\\ref{{prop:harmonic-bases}} (U: $(\\Re Y_{{m,n,j}},\\Im Y_{{m,n,j}},0)$ with $m=2n-4$; "
           f"V: $\\sqrt2(0,0,\\Re Y_{{m,n,j}})$ with $m=2n$), $\\deg\\bar W={D}$, {len(modes)} coefficients.}}\\label{{tab:coefficients}}\\\\",
           "\\toprule", head + "\\\\", "\\midrule", "\\endfirsthead",
           "\\toprule", head + "\\\\", "\\midrule", "\\endhead", "\\bottomrule", "\\endfoot"]
    for i in range(per):
        cells = []
        for c in range(columns):
            k = i + c * per
            if k < n:
                m, v = rows[k]
                cells.append(f"{m.l} & {m.kind} & {m.m} & {m.n} & {m.j} & \\texttt{{{repr(float(v))}}}")
            else:
                cells.append(" & & & & & ")
        out.append(" & ".join(cells) + "\\\\")
    out.append("\\end{longtable}")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--coefficients", default="data/Wbar_D40.json")
    ap.add_argument("--out", default=None)
    ap.add_argument("--columns", type=int, default=2)
    ap.add_argument("--max-degree", type=int, default=None, help="only list coefficients of degree <= this")
    args = ap.parse_args()
    modes, values, data = load_coefficients(args.coefficients)
    D = data["degree"]
    out = Path(args.out or f"certificate/output/coefficients_D{D}.tex")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(latex_longtable(modes, values, D, args.columns, args.max_degree))
    print(f"wrote {out} ({len(modes)} coefficients)")


if __name__ == "__main__":
    main()
